import { readFile, readdir, mkdir, copyFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const config=JSON.parse(await readFile('repo.config.json','utf8'));
const distribution=config.distribution;
const manifest=JSON.parse(await readFile(`${distribution.source}/manifest.json`,'utf8'));
const filename=`${manifest.id}@${manifest.version}.zip`;
await mkdir('pool',{recursive:true});
await copyFile(`build/dist/${filename}`,`pool/${filename}`);
const cli=resolve('node_modules/@valenced/plugin-cli/bin/valenced-plugin.js');
const result=spawnSync(process.execPath,[cli,'generate-index','--dist','pool','--base-url',`https://raw.githubusercontent.com/${distribution.repository}/refs/heads/main/pool`,'--out','index.json'],{stdio:'inherit'});
if(result.status!==0)throw new Error('Official repository index generation failed');
const index=JSON.parse(await readFile('index.json','utf8'));
if(index.plugins[manifest.id].channels.latest&&manifest.version.includes('-'))throw new Error('Prereleases must stay on beta');
await mkdir(distribution.directory,{recursive:true});
await copyFile('index.json',`${distribution.directory}/index.json`);
await copyFile(`pool/${filename}`,`${distribution.directory}/${distribution.archive}`);
console.log(`Prepared ${filename}; root and previous repository URLs are preserved. Commit these changes to main to publish.`);
